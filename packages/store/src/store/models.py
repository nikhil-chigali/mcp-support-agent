"""SQLAlchemy models for the Hearth & Kettle store.

Translated from the Store design SQL. Conventions:
- Money is integer cents (``*_cents``), never floats.
- Status columns are VARCHAR + CHECK, not Postgres ENUM, so adding a value
  later is an ordinary constraint swap in a migration.
- R7 and R8 are repeated here as CHECK constraints, on top of the policy code.
"""

import enum
from datetime import date, datetime
from typing import Any

from sqlalchemy import (
    BigInteger,
    CheckConstraint,
    Date,
    DateTime,
    Enum,
    ForeignKey,
    Identity,
    Index,
    Integer,
    MetaData,
    Text,
    func,
)
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

# Every constraint and index gets a predictable name. Alembic needs the name to
# drop or replace a constraint later, e.g. when a status gains a new value.
NAMING_CONVENTION = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)

    # Every datetime column is TIMESTAMPTZ.
    type_annotation_map = {datetime: DateTime(timezone=True)}


# --- Status values --------------------------------------------------------


class OrderStatus(enum.StrEnum):
    PLACED = "placed"
    SHIPPED = "shipped"
    DELIVERED = "delivered"
    LOST = "lost"
    CANCELLED = "cancelled"


class RefundMethod(enum.StrEnum):
    ORIGINAL_PAYMENT = "original_payment"
    STORE_CREDIT = "store_credit"


class ReplacementStatus(enum.StrEnum):
    CREATED = "created"
    SHIPPED = "shipped"


class ReturnStatus(enum.StrEnum):
    AWAITING = "awaiting"
    RECEIVED = "received"


class TicketStatus(enum.StrEnum):
    OPEN = "open"
    WAITING = "waiting"
    RESOLVED = "resolved"
    ESCALATED = "escalated"


class MessageAuthor(enum.StrEnum):
    CUSTOMER = "customer"
    AGENT = "agent"
    HUMAN = "human"


def text_enum(enum_cls: type[enum.StrEnum], name: str) -> Enum:
    """A StrEnum stored as VARCHAR(32) with a CHECK constraint, not a Postgres ENUM.

    - native_enum=False: no CREATE TYPE; the column is a plain VARCHAR.
    - create_constraint=True: SQLAlchemy adds CHECK (col IN (...)). It is off by default.
    - values_callable: store "placed", not the member name "PLACED".
    - length=32: room for longer values later without widening the column.
    - name: feeds the naming convention, so the CHECK is called ck_<table>_<name>.
    """
    return Enum(
        enum_cls,
        name=name,
        native_enum=False,
        create_constraint=True,
        length=32,
        values_callable=lambda cls: [member.value for member in cls],
        validate_strings=True,
    )


def pk() -> Any:
    """BIGINT primary key, generated by Postgres (an identity column, not BIGSERIAL)."""
    return mapped_column(BigInteger, Identity(), primary_key=True)


def created_at() -> Any:
    return mapped_column(server_default=func.now())


# --- Tables ---------------------------------------------------------------


class Customer(Base):
    __tablename__ = "customers"

    id: Mapped[int] = pk()
    name: Mapped[str] = mapped_column(Text)
    email: Mapped[str] = mapped_column(Text, unique=True)
    created_at: Mapped[datetime] = created_at()


# Case-insensitive name search: WHERE lower(name) LIKE lower(:q). An expression
# index has to name the real column, so it is declared after the class.
Index("ix_customers_name_lower", func.lower(Customer.name))


class Product(Base):
    __tablename__ = "products"
    __table_args__ = (CheckConstraint("price_cents > 0", name="price_positive"),)

    id: Mapped[int] = pk()
    sku: Mapped[str] = mapped_column(Text, unique=True)
    name: Mapped[str] = mapped_column(Text)
    price_cents: Mapped[int] = mapped_column(Integer)


class Order(Base):
    __tablename__ = "orders"
    __table_args__ = (
        # Each status must carry the timestamp that proves it.
        CheckConstraint(
            "status NOT IN ('shipped', 'delivered', 'lost') OR shipped_at IS NOT NULL",
            name="shipped_has_shipped_at",
        ),
        CheckConstraint(
            "status <> 'delivered' OR delivered_at IS NOT NULL",
            name="delivered_has_delivered_at",
        ),
        CheckConstraint(
            "status <> 'cancelled' OR (cancelled_at IS NOT NULL AND shipped_at IS NULL)",
            name="cancelled_never_shipped",
        ),
    )

    id: Mapped[int] = pk()
    customer_id: Mapped[int] = mapped_column(ForeignKey("customers.id"), index=True)
    status: Mapped[OrderStatus] = mapped_column(text_enum(OrderStatus, "status"))
    placed_at: Mapped[datetime]
    shipped_at: Mapped[datetime | None]
    delivered_at: Mapped[datetime | None]
    expected_by: Mapped[date] = mapped_column(Date)
    cancelled_at: Mapped[datetime | None]


class OrderItem(Base):
    __tablename__ = "order_items"
    __table_args__ = (
        CheckConstraint("qty > 0", name="qty_positive"),
        CheckConstraint("unit_price_cents > 0", name="unit_price_positive"),
        # R8: an item can never be refunded past what was paid for it.
        CheckConstraint(
            "refunded_cents BETWEEN 0 AND qty * unit_price_cents",
            name="r8_refund_cap",
        ),
    )

    id: Mapped[int] = pk()
    order_id: Mapped[int] = mapped_column(ForeignKey("orders.id"), index=True)
    product_id: Mapped[int] = mapped_column(ForeignKey("products.id"))
    qty: Mapped[int] = mapped_column(Integer)
    # The price at the time of the order; products.price_cents can change later.
    unit_price_cents: Mapped[int] = mapped_column(Integer)
    refunded_cents: Mapped[int] = mapped_column(Integer, server_default="0")


class Refund(Base):
    __tablename__ = "refunds"
    __table_args__ = (
        CheckConstraint("amount_cents > 0", name="amount_positive"),
        CheckConstraint("rule IN ('R1', 'R2', 'R3', 'R4', 'R5')", name="rule_pays_out"),
        # R7: refunds over $200 need a named manager.
        CheckConstraint(
            "amount_cents <= 20000 OR approved_by IS NOT NULL",
            name="r7_manager_approval",
        ),
    )

    id: Mapped[int] = pk()
    order_item_id: Mapped[int] = mapped_column(ForeignKey("order_items.id"), index=True)
    amount_cents: Mapped[int] = mapped_column(Integer)
    method: Mapped[RefundMethod] = mapped_column(text_enum(RefundMethod, "method"))
    reason: Mapped[str] = mapped_column(Text)
    rule: Mapped[str] = mapped_column(Text)
    approved_by: Mapped[str | None] = mapped_column(Text)
    idempotency_key: Mapped[str] = mapped_column(Text, unique=True)
    # Catches a reused idempotency key sent with a different body.
    request_hash: Mapped[str] = mapped_column(Text)
    created_at: Mapped[datetime] = created_at()


class Replacement(Base):
    __tablename__ = "replacements"

    id: Mapped[int] = pk()
    order_item_id: Mapped[int] = mapped_column(ForeignKey("order_items.id"), index=True)
    status: Mapped[ReplacementStatus] = mapped_column(
        text_enum(ReplacementStatus, "status"),
        server_default=ReplacementStatus.CREATED.value,
    )
    idempotency_key: Mapped[str] = mapped_column(Text, unique=True)
    created_at: Mapped[datetime] = created_at()


class Return(Base):
    __tablename__ = "returns"
    __table_args__ = (
        # A return belongs to exactly one remedy: a refund or a replacement.
        CheckConstraint(
            "num_nonnulls(refund_id, replacement_id) = 1",
            name="one_remedy",
        ),
    )

    id: Mapped[int] = pk()
    order_item_id: Mapped[int] = mapped_column(ForeignKey("order_items.id"), index=True)
    refund_id: Mapped[int | None] = mapped_column(ForeignKey("refunds.id"))
    replacement_id: Mapped[int | None] = mapped_column(ForeignKey("replacements.id"))
    status: Mapped[ReturnStatus] = mapped_column(
        text_enum(ReturnStatus, "status"),
        server_default=ReturnStatus.AWAITING.value,
    )
    created_at: Mapped[datetime] = created_at()


class Ticket(Base):
    """A support ticket. No customer or order link on purpose: finding those is the agent's job."""

    __tablename__ = "tickets"

    id: Mapped[int] = pk()
    customer_email: Mapped[str] = mapped_column(Text)
    subject: Mapped[str] = mapped_column(Text)
    body: Mapped[str] = mapped_column(Text)
    status: Mapped[TicketStatus] = mapped_column(
        text_enum(TicketStatus, "status"),
        server_default=TicketStatus.OPEN.value,
    )
    # When the customer filed it: the date the refund policy judges against.
    # No default; the seed and the eval harness always set it.
    created_at: Mapped[datetime]
    resolved_at: Mapped[datetime | None]


class TicketMessage(Base):
    __tablename__ = "ticket_messages"

    id: Mapped[int] = pk()
    ticket_id: Mapped[int] = mapped_column(ForeignKey("tickets.id"), index=True)
    author: Mapped[MessageAuthor] = mapped_column(text_enum(MessageAuthor, "author"))
    body: Mapped[str] = mapped_column(Text)
    created_at: Mapped[datetime] = created_at()


class AuditLog(Base):
    __tablename__ = "audit_log"

    id: Mapped[int] = pk()
    actor: Mapped[str] = mapped_column(Text)  # API key name, e.g. "mcp-server"
    case_id: Mapped[str | None] = mapped_column(Text, index=True)  # from X-Case-Id
    action: Mapped[str] = mapped_column(Text)  # "refund.create", "order.cancel", ...
    entity: Mapped[str] = mapped_column(Text)
    entity_id: Mapped[int | None] = mapped_column(BigInteger)
    payload_json: Mapped[dict[str, Any]] = mapped_column(JSONB)
    created_at: Mapped[datetime] = created_at()
